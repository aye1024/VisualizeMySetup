const byId = new Map(parts.map((part) => [part.id, part]))

export function getPart(id: string): Part {
  const part = byId.get(id)
  if (!part) throw new Error(`Missing catalog part ${id}`)
  return part
}

export function referralUrl(part: Pick<Part, 'name'>): string {
  return `https://www.amazon.com/s?k=${encodeURIComponent(part.name)}`
}

